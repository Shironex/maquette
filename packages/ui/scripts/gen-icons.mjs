const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const coreDir = resolve(root, 'node_modules/@phosphor-icons/core');
const version = JSON.parse(readFileSync(resolve(coreDir, 'package.json'), 'utf8')).version;

const entries = ICON_NAMES.map(name => {
  // `-fill` names come from the fill weight, the rest from regular.
  const weight = name.endsWith('-fill') ? 'fill' : 'regular';
  const svg = readFileSync(resolve(coreDir, 'assets', weight, `${name}.svg`), 'utf8');
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map(m => m[1]);
  if (paths.length !== 1) throw new Error(`${name}: expected one path, found ${paths.length}`);
  return `  '${name}': '${paths[0]}',`;
});

writeFileSync(
  resolve(root, 'src/icons/paths.ts'),
  `// Generated by packages/ui/scripts/gen-icons.mjs from @phosphor-icons/core ${version} (regular, MIT). Do not edit.\n\nexport const ICON_PATHS = {\n${entries.join('\n')}\n} as const;\n\nexport type IconName = keyof typeof ICON_PATHS;\n`
);
console.log(`${ICON_NAMES.length} icons written from @phosphor-icons/core ${version}`);
