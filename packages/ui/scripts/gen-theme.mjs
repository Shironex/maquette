import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildTheme, themeNames } from './theme.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(resolve(root, 'tokens.json'), 'utf8'));

writeFileSync(resolve(root, 'src/styles/theme.css'), buildTheme(tokens));
writeFileSync(
  resolve(root, 'src/lib/theme-names.ts'),
  `// Generated by packages/ui/scripts/gen-theme.mjs from tokens.json. Do not edit.\n\nexport const THEME_NAMES = ${JSON.stringify(themeNames(tokens), null, 2)} as const;\n`
);
console.log('theme.css and theme-names.ts written');
