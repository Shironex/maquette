/**
 * Builds the Tailwind v4 theme from the kit's tokens.json. Shared by the
 * generator script and the drift test, so both read the same rules.
 *
 * The raw tokens keep the kit's names as plain custom properties on :root
 * (`--bg-app`, `--text-dim`), so a later light theme only has to redefine them.
 * `@theme inline` maps them onto short utility names (`bg-app`, `text-fg-dim`).
 */

/** Tokens the screens canvas uses on top of tokens.json. */
export const EXTRA_COLORS = [
  {
    name: 'clay-line',
    value: 'rgba(196,125,96,0.55)',
    usage: 'Clay outline on selected stages, rows and dashed drop targets.',
  },
  {
    name: 'studio',
    value: '#312f2b',
    usage: 'Graphite studio ground behind model renders; Blender thumbnails use the same backdrop.',
  },
];

/** Raw token name to utility color name. */
const COLOR_ALIASES = {
  'bg-app': 'app',
  'bg-panel': 'panel',
  'bg-raised': 'raised',
  'bg-hover': 'hover',
  text: 'fg',
  'text-dim': 'fg-dim',
  'text-mute': 'fg-mute',
};

function resolveRef(value) {
  const match = /^\{(.+)\}$/.exec(value);
  return match ? `var(--${match[1]})` : value;
}

export function buildTheme(tokens) {
  const colors = [
    ...tokens.color.tokens.map(t => ({ name: t.name, value: t.value.dark })),
    ...EXTRA_COLORS,
  ];
  const lines = [];
  lines.push('/* Generated by packages/ui/scripts/gen-theme.mjs from tokens.json. Do not edit. */');
  lines.push('');
  lines.push(':root {');
  lines.push('  color-scheme: dark;');
  for (const c of colors) lines.push(`  --${c.name}: ${resolveRef(c.value)};`);
  lines.push('}');
  lines.push('');
  lines.push('@theme inline {');
  lines.push('  --color-*: initial;');
  for (const c of colors)
    lines.push(`  --color-${COLOR_ALIASES[c.name] ?? c.name}: var(--${c.name});`);
  lines.push('}');
  lines.push('');
  lines.push('@theme {');
  lines.push(`  --font-sans: ${tokens.type.families.sans};`);
  lines.push(`  --font-mono: ${tokens.type.families.mono};`);
  for (const group of tokens.type.groups) {
    for (const s of group.styles) {
      lines.push(`  --text-${s.name}: ${s.fontSize};`);
      lines.push(`  --text-${s.name}--line-height: ${s.lineHeight};`);
      if (s.letterSpacing) lines.push(`  --text-${s.name}--letter-spacing: ${s.letterSpacing};`);
      lines.push(`  --text-${s.name}--font-weight: ${s.fontWeight};`);
    }
  }
  lines.push('  --spacing: 4px;');
  for (const r of tokens.radius.tokens) lines.push(`  --${r.name}: ${r.value};`);
  for (const s of tokens.shadow.tokens) lines.push(`  --${s.name}: ${s.value};`);
  lines.push('  --animate-spin: spin 900ms linear infinite;');
  lines.push('  --animate-pulse: pulse 1.4s ease-in-out infinite;');
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

/** Names tailwind-merge has to know, so `text-body` and `text-fg` never collide. */
export function themeNames(tokens) {
  return {
    colors: [
      ...tokens.color.tokens.map(t => COLOR_ALIASES[t.name] ?? t.name),
      ...EXTRA_COLORS.map(c => c.name),
    ],
    text: tokens.type.groups.flatMap(g => g.styles.map(s => s.name)),
    radius: tokens.radius.tokens.map(r => r.name.replace(/^radius-/, '')),
    shadow: tokens.shadow.tokens.map(s => s.name.replace(/^shadow-/, '')),
  };
}
