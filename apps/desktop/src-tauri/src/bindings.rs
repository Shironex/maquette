/// Writes the bindings to [`GENERATED_FILE`].
///
/// # Errors
///
/// Fails when a type cannot be represented in TypeScript or the file cannot
/// be written.
pub fn export() -> Result<(), Box<dyn std::error::Error>> {
    let path = PathBuf::from(GENERATED_FILE);
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    builder().export(Typescript::default().header(HEADER), &path)?;
    Ok(())
}

