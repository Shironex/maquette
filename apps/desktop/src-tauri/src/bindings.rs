//! The tauri-specta builder and the TypeScript file it writes. The export
//! runs from `cargo test`, so a changed command or type regenerates the file
//! and the diff shows up in review.

use std::path::PathBuf;

use specta_typescript::Typescript;
use tauri_specta::{Builder, ErrorHandlingMode, collect_commands, collect_events};

use crate::commands::{app, assets, dialogs, inbox, pipeline, project, toolchain, workspace};
use crate::events::{InboxChanged, PipelineUpdate};

/// Compile time path, so the export never depends on the working folder.
pub const GENERATED_FILE: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../web/src/ipc/generated/bindings.ts"
);

const HEADER: &str = "\
// Generated by `cargo test -p maquette-desktop` (tauri-specta). Do not edit.
";

pub fn builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        .error_handling(ErrorHandlingMode::Throw)
        .commands(collect_commands![
            app::app_bootstrap,
            workspace::workspace_inspect,
            workspace::workspace_create,
            workspace::workspace_open,
            workspace::workspace_save_config,
            workspace::workspace_cache_size,
            workspace::workspace_clear_cache,
            toolchain::toolchain_detect,
            toolchain::toolchain_locate,
            toolchain::toolchain_reset,
            project::project_create,
            project::project_update,
            project::project_inspect_repo,
            project::project_scan_import,
            dialogs::dialog_pick_folder,
            dialogs::dialog_pick_file,
            assets::asset_add,
            assets::asset_move,
            assets::asset_open_in_blender,
            pipeline::pipeline_get,
            pipeline::pipeline_run,
            pipeline::pipeline_cancel,
            pipeline::pipeline_log,
            pipeline::pipeline_save_presets,
            inbox::inbox_list,
            inbox::inbox_reprocess,
            inbox::inbox_set_kind,
            inbox::inbox_accept,
            inbox::inbox_open_in_blender,
        ])
        .events(collect_events![PipelineUpdate, InboxChanged])
        .types(&maquette_core::types())
}

/// Writes the bindings to [`GENERATED_FILE`].
///
/// # Errors
///
/// Fails when a type cannot be represented in TypeScript or the file cannot
/// be written.
pub fn export() -> Result<(), Box<dyn std::error::Error>> {
    let path = PathBuf::from(GENERATED_FILE);
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    builder().export(Typescript::default().header(HEADER), &path)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn export_writes_the_bindings_into_the_web_app() {
        export().expect("export bindings");
        let text = std::fs::read_to_string(GENERATED_FILE).expect("read bindings");
        assert!(text.starts_with("// Generated by"));
        for command in [
            "appBootstrap",
            "toolchainDetect",
            "workspaceSaveConfig",
            "pipelineRun",
            "inboxAccept",
            "assetMove",
        ] {
            assert!(text.contains(command), "bindings miss {command}");
        }
        for event in ["pipelineUpdate", "inboxChanged"] {
            assert!(text.contains(event), "bindings miss the {event} event");
        }
        let resolved = PathBuf::from(GENERATED_FILE)
            .canonicalize()
            .expect("resolve bindings path");
        assert!(resolved.ends_with("apps/web/src/ipc/generated/bindings.ts"));
    }
}
